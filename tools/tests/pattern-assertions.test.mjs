// Helper self-tests only. These synthetic pages are not product acceptance evidence.
import assert from 'node:assert/strict';
import { assertSurface, assertKeyboardReachable, assertNativeForm, assertFeedback, assertRetained,
  assertFieldAssociation, assertActiveDescendant, assertValidFocus, applyTextAdaptation, assertTextFits, dispatchComposingKey } from '../pattern-assertions.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '../browser-runtime/node_modules/playwright/index.mjs');
const { default: AxeBuilder } = await import(process.env.AXE_PLAYWRIGHT_MODULE || '../browser-runtime/node_modules/@axe-core/playwright/dist/index.mjs');
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_EXECUTABLE });
const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
const page = await context.newPage();
const html = `<!doctype html><html lang="en"><title>Assertion fixture</title><style>input:focus-visible,button:focus-visible{outline:3px solid #246;outline-offset:2px}body{color:#111;background:#fff}p{font-size:16px}</style><main><h1>Draft</h1><form method="post" action="/preview"><input type="hidden" name="csrf_token" value="synthetic"><label for="title">Title</label><input id="title" name="title" value="Retained" aria-describedby="title-help title-error"><small id="title-help">Public title</small><small id="title-error" hidden></small><button type="submit">Preview</button></form><p role="alert">Correct the date</p><p role="status">Not executed</p></main></html>`;
try {
  await page.route('http://127.0.0.1:17893/**', route => route.fulfill({ contentType: 'text/html', body: html }));
  await page.goto('http://127.0.0.1:17893/');
  assert.equal((await assertSurface(page)).accessibility, 'not_run');
  assert.equal((await assertSurface(page, { AxeBuilder })).accessibility, 'passed');
  await assertNativeForm(page.locator('form'));
  await assertRetained(page.locator('form'), { title: 'Retained' });
  await assertFeedback(page.locator('[role=alert]'), { kind: 'error', text: /Correct/ });
  await assertFeedback(page.locator('[role=status]'), { text: 'Not executed' });
  await assertKeyboardReachable(page, page.getByRole('button', { name: 'Preview' }));
  await assertValidFocus(page, { within: 'form' });
  await assertFieldAssociation(page.locator('#title'), { name: 'Title', description: 'Public title' });
  await page.locator('#title').evaluate(el => el.setAttribute('aria-describedby', 'missing-help'));
  await assert.rejects(assertFieldAssociation(page.locator('#title')));
  await page.locator('#title').evaluate(el => el.setAttribute('aria-describedby', 'title-help title-error'));
  await assert.rejects(assertRetained(page.locator('form'), { title: 'Lost' }));
  await assert.rejects(assertRetained(page.locator('form'), { csrf_token: 'synthetic' }));
  await assert.rejects(assertFeedback(page.locator('[role=status]'), { kind: 'error' }));
  await page.locator('form').evaluate(el => el.method = 'get');
  await assert.rejects(assertNativeForm(page.locator('form'), { method: 'get' }));
  await page.locator('[name=csrf_token]').evaluate(el => el.remove());
  await assertNativeForm(page.locator('form'), { method: 'get' });
  await page.locator('label').evaluate(el => el.textContent = '');
  await assert.rejects(assertNativeForm(page.locator('form'), { method: 'get' }));
  await assert.rejects(assertFieldAssociation(page.locator('#title')));
  await assert.rejects(assertSurface(page, { AxeBuilder }));
  await page.reload();
  await page.locator('#title').evaluate(el => {
    el.setAttribute('role', 'combobox'); el.setAttribute('aria-expanded', 'true');
    el.setAttribute('aria-controls', 'results'); el.setAttribute('aria-activedescendant', 'one');
    el.insertAdjacentHTML('afterend', '<div id="results" role="listbox" aria-label="Titles"><div id="one" role="option" aria-selected="true">One</div></div>');
  });
  await assertActiveDescendant(page.locator('#title'));
  await page.locator('#one').evaluate(el => el.hidden = true);
  await assert.rejects(assertActiveDescendant(page.locator('#title')));
  await page.locator('#one').evaluate(el => { el.hidden = false; el.style.visibility = 'hidden'; });
  await assert.rejects(assertActiveDescendant(page.locator('#title')));
  await page.locator('#one').evaluate(el => { el.style.visibility = ''; el.removeAttribute('aria-selected'); });
  await assert.rejects(assertActiveDescendant(page.locator('#title')));
  await page.reload();
  await page.locator('main').evaluate(el => el.insertAdjacentHTML('beforeend', `<style>#native-check{position:absolute;width:0;height:0;opacity:0}#native-check:focus-visible+span{outline:3px solid #246}#check-track{display:inline-block;width:30px;height:20px}.fixture-sr{position:absolute;width:1px;height:1px;overflow:hidden;clip:rect(0,0,0,0)}</style><label><input id="native-check" type="checkbox"><span id="check-track"></span>Native checkbox</label><label class="fixture-sr" for="title">Hidden helper label</label>`));
  await assertKeyboardReachable(page, page.locator('#native-check'), { focusIndicator: page.locator('#check-track') });
  await page.keyboard.press('Space');
  assert.equal(await page.locator('#native-check').isChecked(), true);
  await assertTextFits(page.locator('label'));
  await page.reload();
  const beforeFont = await page.locator('p').first().evaluate(el => parseFloat(getComputedStyle(el).fontSize));
  assert.deepEqual(await applyTextAdaptation(page), { scale: 2, spacing: true, elements: await page.locator('body,body *').count() });
  assert.equal(await page.locator('p').first().evaluate(el => parseFloat(getComputedStyle(el).fontSize)), beforeFont * 2);
  await assertTextFits(page.locator('p'));
  await page.locator('p').first().evaluate(el => { el.style.height = '5px'; el.style.overflow = 'hidden'; });
  await assert.rejects(assertTextFits(page.locator('p')));
  await page.reload();
  await page.locator('#title').evaluate(el => { el._keys = []; el.addEventListener('keydown', event => el._keys.push({ key: event.key, composing: event.isComposing, code: event.keyCode })); });
  await dispatchComposingKey(page.locator('#title'), 'Enter');
  await dispatchComposingKey(page.locator('#title'), 'Escape', { legacy: true });
  assert.deepEqual(await page.locator('#title').evaluate(el => el._keys), [{ key: 'Enter', composing: true, code: 0 }, { key: 'Escape', composing: false, code: 229 }]);
  await page.locator('main').evaluate(el => el.style.width = '800px');
  await assert.rejects(assertSurface(page));
  console.log('PASS helper self-tests: Axe failure detection, native form/CSRF/GET, retained fields, announcements, real Tab/focus, computed AX name/IDREFs, active descendants, 200% text/spacing/clipping, synthetic IME probes, overflow. Synthetic DOM only; not Odyssey product acceptance.');
} finally { await context.close(); await browser.close(); }
